import { CaptionSegment } from '../types';

/**
 * Format seconds to HH:MM:SS,mmm (SRT standard)
 */
export function formatSRTTime(seconds: number): string {
  const pad = (num: number, size: number) => num.toString().padStart(size, '0');
  const totalSeconds = Math.max(0, seconds);
  const hrs = Math.floor(totalSeconds / 3600);
  const mins = Math.floor((totalSeconds % 3600) / 60);
  const secs = Math.floor(totalSeconds % 60);
  const millis = Math.floor((totalSeconds % 1) * 1000);

  return `${pad(hrs, 2)}:${pad(mins, 2)}:${pad(secs, 2)},${pad(millis, 3)}`;
}

/**
 * Format seconds to HH:MM:SS.mmm (VTT standard)
 */
export function formatVTTTime(seconds: number): string {
  return formatSRTTime(seconds).replace(',', '.');
}

/**
 * Format seconds to friendly mm:ss or mm:ss.d
 */
export function formatDisplayTime(seconds: number, withDecimals: boolean = false): string {
  if (isNaN(seconds) || seconds < 0) return '0:00';
  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  const pad = (n: number) => n.toString().padStart(2, '0');

  if (withDecimals) {
    const tenths = Math.floor((seconds % 1) * 10);
    return `${mins}:${pad(secs)}.${tenths}`;
  }
  return `${mins}:${pad(secs)}`;
}

/**
 * Strip all Unicode emoji characters, symbols, and pictographs from text
 */
export function stripEmojis(text: string): string {
  if (!text) return '';
  return text
    // Strip standard unicode emoji ranges, pictographs, transport, flags, modifiers
    .replace(/[\u{1F600}-\u{1F64F}\u{1F300}-\u{1F5FF}\u{1F680}-\u{1F6FF}\u{1F700}-\u{1F77F}\u{1F780}-\u{1F7FF}\u{1F800}-\u{1F8FF}\u{1F900}-\u{1F9FF}\u{1FA00}-\u{1FA6F}\u{1FA70}-\u{1FAFF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{2300}-\u{23FF}\u{2B50}\u{200D}\u{FE0F}]/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Generate standard .SRT string
 */
export function generateSRT(segments: CaptionSegment[], removeEmojis: boolean = false): string {
  return segments
    .map((seg, idx) => {
      const startStr = formatSRTTime(seg.start);
      const endStr = formatSRTTime(seg.end);
      const emojiPrefix = !removeEmojis && seg.emoji ? `${seg.emoji} ` : '';
      const text = removeEmojis ? stripEmojis(seg.text) : seg.text;
      return `${idx + 1}\n${startStr} --> ${endStr}\n${emojiPrefix}${text.trim()}\n`;
    })
    .join('\n');
}

/**
 * Generate standard .VTT string
 */
export function generateVTT(segments: CaptionSegment[], removeEmojis: boolean = false): string {
  const body = segments
    .map((seg, idx) => {
      const startStr = formatVTTTime(seg.start);
      const endStr = formatVTTTime(seg.end);
      const emojiPrefix = !removeEmojis && seg.emoji ? `${seg.emoji} ` : '';
      const text = removeEmojis ? stripEmojis(seg.text) : seg.text;
      return `${idx + 1}\n${startStr} --> ${endStr}\n${emojiPrefix}${text.trim()}\n`;
    })
    .join('\n');

  return `WEBVTT - Generated by CaptioAI\n\n${body}`;
}

/**
 * Generate plain text transcript
 */
export function generatePlainText(segments: CaptionSegment[], includeTimestamps: boolean = true, removeEmojis: boolean = false): string {
  return segments
    .map((seg) => {
      const text = removeEmojis ? stripEmojis(seg.text) : seg.text;
      if (includeTimestamps) {
        return `[${formatDisplayTime(seg.start)} - ${formatDisplayTime(seg.end)}] ${text}`;
      }
      return text;
    })
    .join('\n');
}

/**
 * Parse an SRT string into CaptionSegment array
 */
export function parseSRT(srtContent: string): CaptionSegment[] {
  const normalized = srtContent.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const blocks = normalized.trim().split(/\n\n+/);
  const segments: CaptionSegment[] = [];

  for (let i = 0; i < blocks.length; i++) {
    const lines = blocks[i].split('\n');
    if (lines.length < 2) continue;

    const timeLineIndex = lines[0].includes('-->') ? 0 : 1;
    if (!lines[timeLineIndex] || !lines[timeLineIndex].includes('-->')) continue;

    const [startRaw, endRaw] = lines[timeLineIndex].split('-->').map((s) => s.trim());
    const textLines = lines.slice(timeLineIndex + 1).join(' ').trim();

    const start = parseTimeString(startRaw);
    const end = parseTimeString(endRaw);

    if (!isNaN(start) && !isNaN(end) && textLines) {
      const wordsArr = textLines.split(/\s+/).filter(Boolean);
      const dur = Math.max(0.2, end - start);
      const words = wordsArr.map((w, wIdx) => ({
        word: w,
        start: Number((start + (wIdx / wordsArr.length) * dur).toFixed(2)),
        end: Number((start + ((wIdx + 1) / wordsArr.length) * dur).toFixed(2)),
        isHighlighted: wIdx === 0,
      }));

      segments.push({
        id: `srt-seg-${i}-${Date.now()}`,
        start,
        end,
        text: textLines,
        emoji: '✨',
        words,
      });
    }
  }

  return formatSegmentsTo1SecondPacing(segments);
}

function parseTimeString(timeStr: string): number {
  const parts = timeStr.replace(',', '.').split(':');
  if (parts.length === 3) {
    const hrs = parseFloat(parts[0]);
    const mins = parseFloat(parts[1]);
    const secs = parseFloat(parts[2]);
    return hrs * 3600 + mins * 60 + secs;
  }
  if (parts.length === 2) {
    const mins = parseFloat(parts[0]);
    const secs = parseFloat(parts[1]);
    return mins * 60 + secs;
  }
  return parseFloat(timeStr) || 0;
}

/**
 * Re-chunks subtitle segments into natural, 1-line ~1-second duration captions
 * synchronized to actual speech timestamps.
 * 
 * Rules:
 * 1. Each segment duration targets ~0.8s to 1.25s (1 spoken line).
 * 2. Words are preserved in correct sequence without mid-word cutting.
 * 3. Speech pauses (>0.35s) create a clean cut so no captions appear during silence.
 * 4. Word-level timestamps are strictly preserved.
 */
export function formatSegmentsTo1SecondPacing(segments: CaptionSegment[]): CaptionSegment[] {
  if (!segments || segments.length === 0) return [];

  interface FlattenedWord {
    word: string;
    start: number;
    end: number;
    isHighlighted?: boolean;
    parentEmoji?: string;
    parentSentiment?: string;
    parentReasoning?: string;
  }

  const allWords: FlattenedWord[] = [];

  for (const seg of segments) {
    let rawWords = seg.words && seg.words.length > 0 ? [...seg.words] : [];

    if (rawWords.length === 0 && seg.text) {
      const split = seg.text.trim().split(/\s+/).filter(Boolean);
      const segDur = Math.max(0.2, seg.end - seg.start);
      rawWords = split.map((w, idx) => {
        const wStart = seg.start + (idx / split.length) * segDur;
        const wEnd = seg.start + ((idx + 1) / split.length) * segDur;
        return {
          word: w,
          start: Number(wStart.toFixed(2)),
          end: Number(wEnd.toFixed(2)),
          isHighlighted: (seg.highlightedWords || []).some(
            (hw) => hw.toLowerCase() === w.replace(/[^\w]/g, '').toLowerCase()
          ),
        };
      });
    }

    for (const w of rawWords) {
      allWords.push({
        word: w.word,
        start: Number(w.start.toFixed(2)),
        end: Number(w.end.toFixed(2)),
        isHighlighted: w.isHighlighted,
        parentEmoji: seg.emoji,
        parentSentiment: seg.sentiment,
        parentReasoning: seg.contextReasoning,
      });
    }
  }

  if (allWords.length === 0) return segments;

  // Sort words chronologically
  allWords.sort((a, b) => a.start - b.start);

  const result: CaptionSegment[] = [];
  let chunk: FlattenedWord[] = [];

  const flush = () => {
    if (chunk.length === 0) return;
    const first = chunk[0];
    const last = chunk[chunk.length - 1];
    const text = chunk.map((w) => w.word).join(' ').trim();
    if (!text) return;

    // Pick emoji from words or fallback
    const emoji = chunk.find((w) => w.parentEmoji && w.parentEmoji !== '✨')?.parentEmoji || chunk[0].parentEmoji || '✨';
    const sentiment = chunk.find((w) => w.parentSentiment)?.parentSentiment;
    const reasoning = chunk.find((w) => w.parentReasoning)?.parentReasoning;
    const highlightedWords = chunk.filter((w) => w.isHighlighted).map((w) => w.word);

    result.push({
      id: `seg-1s-${result.length + 1}-${Date.now().toString(36).slice(-4)}`,
      start: Number(first.start.toFixed(2)),
      end: Number(last.end.toFixed(2)),
      text,
      emoji,
      sentiment,
      contextReasoning: reasoning,
      highlightedWords,
      words: chunk.map((w) => ({
        word: w.word,
        start: Number(w.start.toFixed(2)),
        end: Number(w.end.toFixed(2)),
        isHighlighted: !!w.isHighlighted,
      })),
    });

    chunk = [];
  };

  for (let i = 0; i < allWords.length; i++) {
    const currentWord = allWords[i];

    if (chunk.length === 0) {
      chunk.push(currentWord);
      continue;
    }

    const prevWord = chunk[chunk.length - 1];
    const chunkStart = chunk[0].start;
    const pauseGap = currentWord.start - prevWord.end;
    const durationWithWord = currentWord.end - chunkStart;
    const currentDuration = prevWord.end - chunkStart;

    // Split triggers:
    // 1. Natural speech pause (gap > 0.32s between words)
    // 2. Chunk duration reached ~1 second (currentDuration >= 0.85s) and adding this word pushes past 1.25s
    // 3. Chunk has 3-4 words and duration is already at least 0.75s
    const isSpeechPause = pauseGap > 0.32;
    const isOverOneSec = currentDuration >= 0.85 && durationWithWord > 1.25;
    const isNaturalLineBreak = chunk.length >= 4 && currentDuration >= 0.75;

    if (isSpeechPause || isOverOneSec || isNaturalLineBreak) {
      flush();
      chunk.push(currentWord);
    } else {
      chunk.push(currentWord);
    }
  }

  flush();
  return result.length > 0 ? result : segments;
}
